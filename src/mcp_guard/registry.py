"""Allowlisted, hash-pinned tool registry.

Answers two threats from the threat model:

- T3 rug pull: an approved tool silently changes its description or schema.
  Every advertised tool is re-hashed at runtime and compared with the pin in
  ``policy/registry.lock.yaml``. Mismatch -> the tool is disabled and a
  ``RUG_PULL`` event is reported.
- T8 shadowing: a second server advertises a tool with the same name as a
  trusted one. ``pin`` refuses to write a lockfile with duplicate tool names,
  and ``verify`` disables every advertiser of a duplicated name except the
  server that pinned it.

Canonical form (section 5 of the plan): JSON of
``{server, name, description, inputSchema}`` with sorted keys, no whitespace,
UTF-8. Pin = SHA-256 hex of those bytes. No Unicode normalisation is applied
on purpose: an invisible character added to a description is a change.

Tool-description scanning for injected instructions (R7) is a separate check,
added in M3.
"""

from __future__ import annotations

import hashlib
import re
from collections import defaultdict
from dataclasses import dataclass, field
from enum import Enum
from pathlib import Path
from typing import Any, Iterable, Mapping

import yaml

from .models import ToolSpec, canonical_json, qualify, validate_server_name, validate_tool_name

LOCKFILE_VERSION = 1
HASH_ALGORITHM = "sha256"
_HEX64 = re.compile(r"^[0-9a-f]{64}$")

LOCKFILE_HEADER = (
    "# Generated by `mcp-guard pin`. Do not edit by hand.\n"
    "# Review every change to this file in a pull request: a changed hash means\n"
    "# a tool's description or input schema changed.\n"
)


class RegistryError(Exception):
    """Base class for registry failures."""


class LockfileError(RegistryError):
    """The lockfile is missing, malformed or inconsistent."""


class ShadowingError(RegistryError):
    """Two tools share a name (across servers, or twice on one server)."""


# --------------------------------------------------------------------------
# Canonical form and pins


def canonical_tool(spec: ToolSpec) -> bytes:
    return canonical_json(
        {
            "server": spec.server,
            "name": spec.name,
            "description": spec.description,
            "inputSchema": spec.input_schema,
        }
    )


def pin(spec: ToolSpec) -> str:
    """SHA-256 hex digest of the tool's canonical form."""
    return hashlib.sha256(canonical_tool(spec)).hexdigest()


# --------------------------------------------------------------------------
# Lockfile


@dataclass(frozen=True)
class PinnedTool:
    server: str
    name: str
    sha256: str

    @property
    def qualified_name(self) -> str:
        return qualify(self.server, self.name)


@dataclass(frozen=True)
class Lockfile:
    tools: Mapping[str, PinnedTool]  # keyed by qualified name

    def owner_of(self, name: str) -> str | None:
        """Server that pinned the bare tool name ``name``, if any."""
        for t in self.tools.values():
            if t.name == name:
                return t.server
        return None

    def to_dict(self) -> dict[str, Any]:
        return {
            "version": LOCKFILE_VERSION,
            "algorithm": HASH_ALGORITHM,
            "tools": [
                {"server": t.server, "name": t.name, "sha256": t.sha256}
                for t in sorted(self.tools.values(), key=lambda t: (t.server, t.name))
            ],
        }

    def dumps(self) -> str:
        body = yaml.safe_dump(self.to_dict(), sort_keys=False, default_flow_style=False)
        return LOCKFILE_HEADER + body


def check_unique_names(specs: Iterable[ToolSpec]) -> None:
    """Raise ShadowingError if any tool name is advertised more than once."""
    by_name: dict[str, list[str]] = defaultdict(list)
    for s in specs:
        by_name[s.name].append(s.server)
    problems = []
    for name, servers in sorted(by_name.items()):
        if len(servers) > 1:
            problems.append(f"{name!r} advertised by {', '.join(sorted(servers))}")
    if problems:
        raise ShadowingError("duplicate tool names: " + "; ".join(problems))


def build_lockfile(specs: Iterable[ToolSpec]) -> Lockfile:
    """Pin every spec. Refuses duplicate tool names (shadowing)."""
    specs = list(specs)
    check_unique_names(specs)
    tools = {s.qualified_name: PinnedTool(s.server, s.name, pin(s)) for s in specs}
    return Lockfile(tools)


def write_lockfile(path: str | Path, specs: Iterable[ToolSpec]) -> Lockfile:
    lock = build_lockfile(specs)
    path = Path(path)
    path.parent.mkdir(parents=True, exist_ok=True)
    # newline="\n": identical bytes on Windows and Linux, so diffs stay clean.
    with path.open("w", encoding="utf-8", newline="\n") as f:
        f.write(lock.dumps())
    return lock


def parse_lockfile(data: Any, source: str = "<lockfile>") -> Lockfile:
    def fail(msg: str) -> LockfileError:
        return LockfileError(f"{source}: {msg}")

    if not isinstance(data, Mapping):
        raise fail("must be a YAML mapping")
    if data.get("version") != LOCKFILE_VERSION:
        raise fail(f"unsupported version {data.get('version')!r} (expected {LOCKFILE_VERSION})")
    if data.get("algorithm") != HASH_ALGORITHM:
        raise fail(f"unsupported algorithm {data.get('algorithm')!r}")
    entries = data.get("tools")
    if not isinstance(entries, list):
        raise fail("'tools' must be a list")

    tools: dict[str, PinnedTool] = {}
    names: dict[str, str] = {}
    for i, e in enumerate(entries):
        if not isinstance(e, Mapping) or set(e) != {"server", "name", "sha256"}:
            raise fail(f"entry {i} must have exactly server, name, sha256")
        try:
            server = validate_server_name(e["server"])
            name = validate_tool_name(e["name"])
        except ValueError as exc:
            raise fail(f"entry {i}: {exc}") from None
        digest = e["sha256"]
        if not isinstance(digest, str) or not _HEX64.match(digest):
            raise fail(f"entry {i} ({server}.{name}): sha256 must be 64 lowercase hex chars")
        if name in names:
            raise fail(f"tool name {name!r} pinned for both {names[name]} and {server} (shadowing)")
        names[name] = server
        tools[qualify(server, name)] = PinnedTool(server, name, digest)
    return Lockfile(tools)


def load_lockfile(path: str | Path) -> Lockfile:
    path = Path(path)
    try:
        text = path.read_text(encoding="utf-8")
    except FileNotFoundError:
        raise LockfileError(f"{path}: not found; run `mcp-guard pin` first") from None
    try:
        data = yaml.safe_load(text)
    except yaml.YAMLError as exc:
        raise LockfileError(f"{path}: invalid YAML: {exc}") from None
    return parse_lockfile(data, source=str(path))


# --------------------------------------------------------------------------
# Runtime verification


class EventKind(str, Enum):
    RUG_PULL = "RUG_PULL"    # pinned tool's hash changed -> disabled
    UNPINNED = "UNPINNED"    # advertised but not in the lockfile -> disabled
    SHADOWING = "SHADOWING"  # same name from another server -> disabled
    DUPLICATE = "DUPLICATE"  # same server advertises a name twice -> disabled
    MISSING = "MISSING"      # pinned but not advertised -> informational

    def __str__(self) -> str:
        return self.value


#: Events that mean something was refused. MISSING is informational.
BLOCKING_EVENTS = frozenset(
    {EventKind.RUG_PULL, EventKind.UNPINNED, EventKind.SHADOWING, EventKind.DUPLICATE}
)


@dataclass(frozen=True)
class RegistryEvent:
    kind: EventKind
    server: str
    tool: str
    detail: str
    expected: str | None = None
    actual: str | None = None

    @property
    def qualified_name(self) -> str:
        return qualify(self.server, self.tool)

    def __str__(self) -> str:
        return f"{self.kind} {self.qualified_name}: {self.detail}"


@dataclass
class Registry:
    """Tools that passed verification. Only these may be called."""

    enabled: dict[str, ToolSpec] = field(default_factory=dict)
    events: list[RegistryEvent] = field(default_factory=list)

    def is_allowed(self, server: str, tool: str) -> bool:
        return qualify(server, tool) in self.enabled

    def get(self, server: str, tool: str) -> ToolSpec | None:
        return self.enabled.get(qualify(server, tool))

    @property
    def ok(self) -> bool:
        """True if no tool was refused."""
        return not any(e.kind in BLOCKING_EVENTS for e in self.events)

    def events_of(self, kind: EventKind) -> list[RegistryEvent]:
        return [e for e in self.events if e.kind is kind]


def verify(advertised: Iterable[ToolSpec], lock: Lockfile) -> Registry:
    """Check every advertised tool against the lockfile.

    A tool is enabled only if it is pinned, its hash matches, and no other
    server advertises the same name (unless that other server is the one
    that pinned it, in which case only the impostor is disabled).
    """
    advertised = list(advertised)
    registry = Registry()

    by_qname: dict[str, list[ToolSpec]] = defaultdict(list)
    servers_by_name: dict[str, set[str]] = defaultdict(set)
    for s in advertised:
        by_qname[s.qualified_name].append(s)
        servers_by_name[s.name].add(s.server)

    for qname, specs in by_qname.items():
        spec = specs[0]
        if len(specs) > 1:
            registry.events.append(RegistryEvent(
                EventKind.DUPLICATE, spec.server, spec.name,
                f"advertised {len(specs)} times by the same server",
            ))
            continue

        others = servers_by_name[spec.name] - {spec.server}
        if others:
            owner = lock.owner_of(spec.name)
            if owner != spec.server:
                pinned_by = f"pinned by {owner}" if owner else "not pinned by any server"
                registry.events.append(RegistryEvent(
                    EventKind.SHADOWING, spec.server, spec.name,
                    f"name also advertised by {', '.join(sorted(others))}; {pinned_by}",
                ))
                continue

        pinned = lock.tools.get(qname)
        if pinned is None:
            registry.events.append(RegistryEvent(
                EventKind.UNPINNED, spec.server, spec.name, "not in the lockfile",
            ))
            continue

        actual = pin(spec)
        if actual != pinned.sha256:
            registry.events.append(RegistryEvent(
                EventKind.RUG_PULL, spec.server, spec.name,
                "description or input schema changed since it was pinned",
                expected=pinned.sha256, actual=actual,
            ))
            continue

        registry.enabled[qname] = spec

    for qname, pinned in lock.tools.items():
        if qname not in by_qname:
            registry.events.append(RegistryEvent(
                EventKind.MISSING, pinned.server, pinned.name, "pinned but not advertised",
            ))

    registry.events.sort(key=lambda e: (e.server, e.tool, e.kind.value))
    return registry


def specs_from_mcp(server: str, tools: Iterable[Mapping[str, Any]]) -> list[ToolSpec]:
    """Convert an MCP ``tools/list`` result for one server into ToolSpecs."""
    return [ToolSpec.from_mcp(server, t) for t in tools]
