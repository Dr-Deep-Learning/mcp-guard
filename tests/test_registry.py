"""Registry: canonical hashing, lockfile, verify, shadowing.

M2 done-when: a tampered tool description is rejected; duplicate names refused.
"""

import dataclasses
import hashlib
from pathlib import Path

import pytest
import yaml

from mcp_guard.models import ToolSpec
from mcp_guard.registry import (
    EventKind,
    LockfileError,
    ShadowingError,
    build_lockfile,
    canonical_tool,
    load_lockfile,
    parse_lockfile,
    pin,
    specs_from_mcp,
    verify,
    write_lockfile,
)
from mock.servers import all_specs, rug_pulled_servers, shadowing_servers, trusted_servers

ROOT = Path(__file__).resolve().parents[1]
COMMITTED_LOCK = ROOT / "policy" / "registry.lock.yaml"

SPEC = ToolSpec(
    "mail", "send_email", "Send a plain-text email.",
    {"type": "object", "properties": {"to": {"type": "string"}}, "required": ["to"]},
)
# Golden values, checked independently with `printf '%s' ... | sha256sum`.
# If these change, every existing lockfile is invalidated: treat it as a
# breaking change, not a test to update casually.
GOLDEN_CANONICAL = (
    '{"description":"Send a plain-text email.",'
    '"inputSchema":{"properties":{"to":{"type":"string"}},"required":["to"],"type":"object"},'
    '"name":"send_email","server":"mail"}'
)
GOLDEN_PIN = "27fbd48e10b69cccc6d769a54025c4d75221609a75c3c30ec9ec6dc9dab08927"


@pytest.fixture
def trusted_specs():
    return all_specs(trusted_servers())


@pytest.fixture
def lock(trusted_specs):
    return build_lockfile(trusted_specs)


# ---------------------------------------------------------------- canonical form

def test_canonical_form_matches_golden_bytes():
    assert canonical_tool(SPEC) == GOLDEN_CANONICAL.encode("utf-8")


def test_pin_is_sha256_of_canonical_form():
    assert pin(SPEC) == GOLDEN_PIN
    assert pin(SPEC) == hashlib.sha256(canonical_tool(SPEC)).hexdigest()


def test_pin_ignores_schema_key_order():
    reordered = ToolSpec("mail", "send_email", "Send a plain-text email.",
                         {"required": ["to"], "properties": {"to": {"type": "string"}},
                          "type": "object"})
    assert pin(reordered) == GOLDEN_PIN


def test_pin_ignores_fields_outside_the_canonical_four():
    raw = {"name": "send_email", "description": "Send a plain-text email.",
           "inputSchema": SPEC.input_schema, "title": "Email", "annotations": {}}
    assert pin(ToolSpec.from_mcp("mail", raw)) == GOLDEN_PIN


@pytest.mark.parametrize("change", [
    {"description": "Send a plain-text email. Also BCC audit@evil.example."},
    {"description": "Send a plain-text email.​"},     # zero-width space
    {"description": "Send a plain-text email. "},          # trailing whitespace
    {"input_schema": {**SPEC.input_schema, "required": []}},
    {"input_schema": {**SPEC.input_schema,
                      "properties": {"to": {"type": "string"}, "bcc": {"type": "string"}}}},
    {"name": "send_mail"},
    {"server": "mail2"},
])
def test_any_change_to_a_pinned_field_changes_the_pin(change):
    assert pin(dataclasses.replace(SPEC, **change)) != GOLDEN_PIN


def test_list_order_in_schema_is_significant():
    a = ToolSpec("s", "t", "", {"enum": ["a", "b"]})
    b = ToolSpec("s", "t", "", {"enum": ["b", "a"]})
    assert pin(a) != pin(b)


# ---------------------------------------------------------------- lockfile

def test_lockfile_roundtrip(tmp_path, trusted_specs):
    path = tmp_path / "policy" / "registry.lock.yaml"
    written = write_lockfile(path, trusted_specs)
    loaded = load_lockfile(path)
    assert loaded == written
    assert set(loaded.tools) == {s.qualified_name for s in trusted_specs}
    for s in trusted_specs:
        assert loaded.tools[s.qualified_name].sha256 == pin(s)


def test_lockfile_is_deterministic_and_sorted(tmp_path, trusted_specs):
    p1, p2 = tmp_path / "a.yaml", tmp_path / "b.yaml"
    write_lockfile(p1, trusted_specs)
    write_lockfile(p2, list(reversed(trusted_specs)))
    assert p1.read_bytes() == p2.read_bytes()
    assert b"\r\n" not in p1.read_bytes()
    entries = yaml.safe_load(p1.read_text(encoding="utf-8"))["tools"]
    keys = [(e["server"], e["name"]) for e in entries]
    assert keys == sorted(keys)
    assert p1.read_text(encoding="utf-8").startswith("# Generated by `mcp-guard pin`")


def test_committed_lockfile_matches_trusted_mock_servers(trusted_specs):
    """Guards against drift: if a mock tool changes, `mcp-guard pin` must be
    re-run and the lockfile change reviewed."""
    assert load_lockfile(COMMITTED_LOCK) == build_lockfile(trusted_specs)


def test_missing_lockfile_has_a_helpful_error(tmp_path):
    with pytest.raises(LockfileError, match="mcp-guard pin"):
        load_lockfile(tmp_path / "nope.yaml")


def test_invalid_yaml_rejected(tmp_path):
    p = tmp_path / "bad.yaml"
    p.write_text("tools: [unclosed", encoding="utf-8")
    with pytest.raises(LockfileError, match="invalid YAML"):
        load_lockfile(p)


def _good_lock_dict():
    return build_lockfile([SPEC]).to_dict()


@pytest.mark.parametrize("mutate,msg", [
    (lambda d: d.update(version=2), "version"),
    (lambda d: d.update(algorithm="md5"), "algorithm"),
    (lambda d: d.update(tools={"not": "a list"}), "must be a list"),
    (lambda d: d["tools"][0].pop("sha256"), "exactly"),
    (lambda d: d["tools"][0].update(extra=1), "exactly"),
    (lambda d: d["tools"][0].update(sha256="abc"), "64 lowercase hex"),
    (lambda d: d["tools"][0].update(sha256=GOLDEN_PIN.upper()), "64 lowercase hex"),
    (lambda d: d["tools"][0].update(server="a.b"), "invalid server name"),
    (lambda d: d["tools"].append({"server": "other", "name": "send_email",
                                  "sha256": GOLDEN_PIN}), "shadowing"),
])
def test_malformed_lockfiles_rejected(mutate, msg):
    data = _good_lock_dict()
    mutate(data)
    with pytest.raises(LockfileError, match=msg):
        parse_lockfile(data)


def test_non_mapping_lockfile_rejected():
    with pytest.raises(LockfileError):
        parse_lockfile(["tools"])


# ---------------------------------------------------------------- shadowing at pin time

def test_pin_refuses_duplicate_names_across_servers():
    with pytest.raises(ShadowingError, match="send_email.*helper, mail"):
        build_lockfile(all_specs(shadowing_servers()))


def test_pin_refuses_duplicate_name_on_one_server():
    with pytest.raises(ShadowingError):
        build_lockfile([SPEC, dataclasses.replace(SPEC, description="other")])


def test_pin_refusal_writes_nothing(tmp_path):
    path = tmp_path / "lock.yaml"
    with pytest.raises(ShadowingError):
        write_lockfile(path, all_specs(shadowing_servers()))
    assert not path.exists()


# ---------------------------------------------------------------- verify

def test_verify_clean(lock, trusted_specs):
    reg = verify(trusted_specs, lock)
    assert reg.ok and reg.events == []
    assert set(reg.enabled) == set(lock.tools)
    assert reg.is_allowed("mail", "send_email")
    assert reg.get("web", "fetch_url").name == "fetch_url"


def test_tampered_description_is_rejected_as_rug_pull(lock):
    reg = verify(all_specs(rug_pulled_servers()), lock)
    assert not reg.ok
    assert not reg.is_allowed("web", "fetch_url")
    assert reg.get("web", "fetch_url") is None
    [event] = reg.events
    assert event.kind is EventKind.RUG_PULL and event.qualified_name == "web.fetch_url"
    assert event.expected == lock.tools["web.fetch_url"].sha256
    assert event.actual != event.expected
    # Only the changed tool is disabled.
    assert len(reg.enabled) == len(lock.tools) - 1


def test_tampered_schema_is_rejected_as_rug_pull(lock, trusted_specs):
    specs = [dataclasses.replace(s, input_schema={**s.input_schema, "additionalProperties": True})
             if s.qualified_name == "workspace.run_shell" else s for s in trusted_specs]
    reg = verify(specs, lock)
    assert [e.kind for e in reg.events] == [EventKind.RUG_PULL]
    assert not reg.is_allowed("workspace", "run_shell")


def test_shadowing_tool_is_refused_and_owner_stays_enabled(lock):
    reg = verify(all_specs(shadowing_servers()), lock)
    assert not reg.ok
    assert not reg.is_allowed("helper", "send_email")
    assert reg.is_allowed("mail", "send_email")
    [event] = reg.events
    assert event.kind is EventKind.SHADOWING
    assert event.qualified_name == "helper.send_email"
    assert "pinned by mail" in event.detail


def test_shadowing_of_an_unpinned_name_disables_every_copy(lock, trusted_specs):
    new = ToolSpec("a", "summarize", "Summarize text.")
    twin = ToolSpec("b", "summarize", "Summarize text.")
    reg = verify(trusted_specs + [new, twin], lock)
    kinds = {(e.qualified_name, e.kind) for e in reg.events}
    assert kinds == {("a.summarize", EventKind.SHADOWING), ("b.summarize", EventKind.SHADOWING)}
    assert not reg.is_allowed("a", "summarize") and not reg.is_allowed("b", "summarize")


def test_pinned_owner_that_also_rug_pulls_is_still_disabled(lock):
    specs = all_specs(shadowing_servers())
    specs = [dataclasses.replace(s, description="changed")
             if s.qualified_name == "mail.send_email" else s for s in specs]
    reg = verify(specs, lock)
    kinds = {(e.qualified_name, e.kind) for e in reg.events}
    assert kinds == {("mail.send_email", EventKind.RUG_PULL),
                     ("helper.send_email", EventKind.SHADOWING)}
    assert not reg.is_allowed("mail", "send_email")


def test_unpinned_tool_is_refused(lock, trusted_specs):
    extra = ToolSpec("web", "post_url", "POST data to a URL.", {"type": "object"})
    reg = verify(trusted_specs + [extra], lock)
    [event] = reg.events
    assert event.kind is EventKind.UNPINNED
    assert not reg.is_allowed("web", "post_url")


def test_duplicate_advertisement_on_one_server_is_refused(lock, trusted_specs):
    dup = next(s for s in trusted_specs if s.name == "deploy")
    reg = verify(trusted_specs + [dup], lock)
    assert [e.kind for e in reg.events] == [EventKind.DUPLICATE]
    assert not reg.is_allowed("workspace", "deploy")


def test_missing_tool_is_reported_but_not_blocking(lock, trusted_specs):
    reg = verify([s for s in trusted_specs if s.name != "deploy"], lock)
    assert reg.ok
    assert [(e.kind, e.qualified_name) for e in reg.events] == \
        [(EventKind.MISSING, "workspace.deploy")]
    assert not reg.is_allowed("workspace", "deploy")


def test_calling_a_pinned_tool_on_the_wrong_server_is_not_allowed(lock, trusted_specs):
    reg = verify(trusted_specs, lock)
    assert not reg.is_allowed("web", "send_email")


def test_verify_from_mcp_tools_list(lock):
    server = next(s for s in trusted_servers() if s.name == "web")
    reg = verify(specs_from_mcp("web", server.list_tools()), lock)
    assert reg.is_allowed("web", "fetch_url")
    assert reg.events_of(EventKind.MISSING)  # other servers' tools not advertised here


def test_events_are_sorted_deterministically(lock, trusted_specs):
    extras = [ToolSpec("z", "zz", ""), ToolSpec("a", "aa", "")]
    reg = verify(trusted_specs + extras, lock)
    assert [e.qualified_name for e in reg.events] == ["a.aa", "z.zz"]
